"""Export a history-free public source snapshot + deterministic tar.gz, with a sensitive-content scan.

  .venv/bin/python scripts/export_public.py
Outputs dist/public/quantum-research-governor/, dist/public/quantum-research-governor.tar.gz,
dist/public/SHA256SUMS, dist/public/EXPORT_REPORT.json. Exits non-zero on any scan finding.
"""
import gzip
import hashlib
import io
import json
import re
import shutil
import socket
import sys
import tarfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "dist/public"
NAME = "quantum-research-governor"
MTIME = 1791590400  # 2026-10-10T00:00:00Z, fixed for determinism

INCLUDE_GLOBS = [
    "LICENSE", "requirements.txt", "requirements-dev.txt", ".gitignore",
    "index.html", "main.js", "main.css", "main.py",
    "ui/*.js", "qrg/*.py", "verifier/*.py",
    "scripts/build_packages.py", "scripts/build_packages_r2.py", "scripts/export_public.py",
    "packaging/*.md",
    "experiments/*.py", "tests/*.py", "tests/js/*.mjs",
    "dev/make_fixtures.py", "dev/mock/*.js", "dev/fixtures/*.json",
    "docs/*.md", "docs/submission/SUBMISSION_TEXT.md", "docs/submission/SCIENTIFIC_REFERENCES.md",
    "docs/submission/DEMO_VIDEO_SCRIPT.md",
    "results/circuits.txt", "results/r1_calibration.json", "results/r1_bias_check.json",
]
EXCLUDE = {"docs/submission/OWNER_CHECKLIST_R3.md"}
GENERATED = {
    "README.md": lambda: (ROOT / "packaging/PUBLIC_README.md").read_bytes(),
    "experiment_config.py": lambda: (
        b"# Default experiment for running main.py / qrg.js_api from this source tree.\n"
        b"# The Qollab ZIPs are built by scripts/build_packages_r2.py with a fixed config per package.\n"
        b"# B_Z_FAULT = primary (synthetic phase fault); A_NO_FAULT = clean-state control.\n"
        b"EXPERIMENT = \"B_Z_FAULT\"\n"),
    "dev/fixtures/README.md": lambda: (
        b"# LOCAL test fixtures - NOT Qollab measurements\n\n"
        b"Generated by `dev/make_fixtures.py` from the real Python API on a local, seeded BasicSimulator,\n"
        b"for browser tests with a mocked bridge. Never present these counts as live results.\n"
        b"Real owner-executed Qollab results: `docs/QOLLAB_LIVE_EVIDENCE.md`.\n"),
}

PATTERNS = {  # generic only; private patterns live in the git-ignored .release-denylist
    "home_path": r"(/home/[a-z][a-z0-9_-]+|C:\\Users\\)",
    "ipv4": r"\b(?:\d{1,3}\.){3}\d{1,3}\b",
    "email": r"[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}",
    "private_key_block": r"-----BEGIN [A-Z ]*PRIVATE KEY-----",
    "hex_key_0x64": r"0x[0-9a-fA-F]{64}\b",
    "token_like": r"(sk-[A-Za-z0-9]{16,}|ghp_[A-Za-z0-9]{20,}|xox[bpa]-[A-Za-z0-9-]{10,}|AKIA[0-9A-Z]{16})",
    "credential_assignment": r"(?i)\b(api[_-]?key|password|passwd|secret|private[_-]?key|mnemonic|auth[_-]?token)\s*[:=]\s*['\"][^'\"]{6,}",
    "hostname": re.escape(socket.gethostname()) if len(socket.gethostname()) >= 4 else r"(?!x)x",
}
DENYLIST = ROOT / ".release-denylist"
# Reviewed false positives: (path, pattern, exact match)
ALLOW = {
    ("tests/test_browser.py", "ipv4", "127.0.0.1"),  # local test server
    ("scripts/export_public.py", "ipv4", "127.0.0.1"),  # this allow-list entry itself
}


def private_patterns():
    if not DENYLIST.exists():
        sys.exit("refusing to export: private .release-denylist not found (scan would be incomplete)")
    lines = [l.strip() for l in DENYLIST.read_text().splitlines()]
    return {f"private_{i}": l for i, l in enumerate(lines) if l and not l.startswith("#")}


def collect():
    files = {}
    for g in INCLUDE_GLOBS:
        for p in sorted(ROOT.glob(g)):
            rel = p.relative_to(ROOT).as_posix()
            if p.is_file() and rel not in EXCLUDE and "__pycache__" not in rel:
                files[rel] = p.read_bytes()
    for rel, fn in GENERATED.items():
        files[rel] = fn()
    return dict(sorted(files.items()))


def scan(files):
    findings = []
    patterns = {**PATTERNS, **private_patterns()}
    for rel, data in files.items():
        if rel.startswith(".git/") or rel.endswith((".log",)) or "/.git" in rel:
            findings.append({"file": rel, "pattern": "git_or_log_file", "match": rel})
        text = data.decode("utf-8", errors="replace")
        for name, pat in patterns.items():
            for m in re.finditer(pat, text):
                if (rel, name, m.group(0)) in ALLOW:
                    continue
                shown = m.group(0)[:80] if not name.startswith("private_") else "<private pattern>"
                findings.append({"file": rel, "pattern": name, "match": shown,
                                 "line": text.count("\n", 0, m.start()) + 1})
    return findings


def write_tree(files):
    dest = OUT / NAME
    if dest.exists():
        shutil.rmtree(dest)
    for rel, data in files.items():
        p = dest / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(data)
    return dest


def write_tar(files):
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w", format=tarfile.PAX_FORMAT) as tar:
        dirs = sorted({str(Path(NAME, r).parent.as_posix()) for r in files} | {NAME})
        alldirs = set()
        for d in dirs:
            parts = Path(d).parts
            for i in range(1, len(parts) + 1):
                alldirs.add("/".join(parts[:i]))
        for d in sorted(alldirs):
            ti = tarfile.TarInfo(d)
            ti.type, ti.mode, ti.mtime, ti.uid, ti.gid, ti.uname, ti.gname = tarfile.DIRTYPE, 0o755, MTIME, 0, 0, "", ""
            tar.addfile(ti)
        for rel, data in files.items():
            ti = tarfile.TarInfo(f"{NAME}/{rel}")
            ti.size, ti.mode, ti.mtime, ti.uid, ti.gid, ti.uname, ti.gname = len(data), 0o644, MTIME, 0, 0, "", ""
            tar.addfile(ti, io.BytesIO(data))
    out = OUT / f"{NAME}.tar.gz"
    with open(out, "wb") as fh, gzip.GzipFile(filename="", mode="wb", fileobj=fh, mtime=0, compresslevel=9) as gz:
        gz.write(buf.getvalue())
    return out


def main():
    files = collect()
    findings = scan(files)
    OUT.mkdir(parents=True, exist_ok=True)
    report = {"files": len(files), "bytes": sum(map(len, files.values())), "findings": findings,
              "excluded": sorted(EXCLUDE), "git_metadata": False,
              "file_sha256": {r: hashlib.sha256(d).hexdigest() for r, d in files.items()}}
    (OUT / "EXPORT_REPORT.json").write_text(json.dumps(report, indent=2))
    if findings:
        for f in findings:
            print("FINDING", f)
        print(f"EXPORT BLOCKED: {len(findings)} finding(s)")
        return 1
    tree = write_tree(files)
    tar = write_tar(files)
    sha = hashlib.sha256(tar.read_bytes()).hexdigest()
    (OUT / "SHA256SUMS").write_text(f"{sha}  {tar.name}\n")
    print(f"{len(files)} files -> {tree.relative_to(ROOT)}")
    print(f"{sha}  {tar.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
